server = MCPServer("chainguard-ai-docs")

# Load and index documentation
logger.info(f"Loading documentation from {DOCS_PATH}")
try:
    with open(DOCS_PATH, "r") as f:
        docs_content = f.read()
    docs_index = ChaguardDocsIndex(docs_content)
    logger.info(f"Indexed {len(docs_index.sections)} documentation sections")
    logger.info(f"Found {len(docs_index.images)} container images")
except Exception as e:
    logger.error(f"Failed to load documentation: {e}")
    docs_index = None

# Load image catalog
logger.info(f"Loading image catalog from {CATALOG_PATH}")
catalog = ImagesCatalog(CATALOG_PATH)
if catalog.available:
    logger.info(
        f"Catalog loaded: {catalog.catalog['metadata'].get('total_images', 0)} images"
    )
else:
    logger.warning(
        "Image catalog not available; catalog-based tools will return limited results"
    )


def safe_tool(fn):
    """Wrap a tool so uncaught exceptions are logged and never leak to the client.

    Preserves the 1.x server's behavior: on error, log with a stack trace and
    return a sanitized message instead of the raw exception text.
    """

    @functools.wraps(fn)
    def wrapper(*args, **kwargs):
        try:
            return fn(*args, **kwargs)
        except Exception:
            logger.error(f"Error handling tool call {fn.__name__}", exc_info=True)
            return "An internal error occurred. Please try again or adjust your query."

    return wrapper


DOCS_UNAVAILABLE = "Error: Documentation not loaded. Please check server logs."


@server.tool(
    description="Search across all Chainguard documentation for relevant content"
)
@safe_tool
def search_docs(
    query: Annotated[
        str,
        Field(
            description="Search query (e.g., 'python image security', 'CVE management')"
        ),
    ],
    max_results: Annotated[
        int,
        Field(
            description="Maximum number of results to return (default: 5)",
            le=MAX_RESULTS_CAP,
        ),
    ] = 5,
) -> str:
    if docs_index is None:
        return DOCS_UNAVAILABLE

    query = query[:MAX_INPUT_LEN]
    max_results = min(max_results, MAX_RESULTS_CAP)
    results = docs_index.search(query, max_results)

    if not results:
        return f"No results found for query: {query}"

    response = f"# Search Results for: {query}\n\n"
    for i, result in enumerate(results, 1):
        response += f"## Result {i}: {result['section']}\n\n"
        if result["url"]:
            response += f"{result['url']}\n\n"
        response += f"{result['snippet']}\n\n"
        response += "---\n\n"
    return response


