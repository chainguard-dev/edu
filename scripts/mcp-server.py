server = MCPServer("chainguard-ai-docs", instructions=SERVER_INSTRUCTIONS)

# Load and index documentation
logger.info(f"Loading documentation from {DOCS_PATH}")
try:
    with open(DOCS_PATH, "r") as f:
        docs_content = f.read()
    docs_index = ChaguardDocsIndex(docs_content)
    logger.info(f"Indexed {len(docs_index.sections)} documentation sections")
except Exception as e:
    logger.error(f"Failed to load documentation: {e}")
    docs_index = None

# Load package mappings
logger.info(f"Loading package catalog from {CATALOG_PATH}")
catalog = PackageCatalog(CATALOG_PATH)
if catalog.available:
    logger.info(
        f"Catalog loaded: {catalog.catalog['metadata'].get('total_packages_mapped', 0)} package mappings"
    )
else:
    logger.warning(
        "Package catalog not available; find_package_equivalent will return no results"
    )


def safe_tool(fn):
    """Wrap a tool so uncaught exceptions are logged and never leak to the client.

    Preserves the 1.x server's behavior: on error, log with a stack trace and
    return a sanitized message instead of the raw exception text.
    """

    @functools.wraps(fn)
    def wrapper(*args, **kwargs):
        try:
            return fn(*args, **kwargs)
        except Exception:
            logger.error(f"Error handling tool call {fn.__name__}", exc_info=True)
            return "An internal error occurred. Please try again or adjust your query."

    return wrapper


DOCS_UNAVAILABLE = "Error: Documentation not loaded. Please check server logs."


@server.tool(
    description="Search across all Chainguard documentation for relevant content"
)
@safe_tool
def search_docs(
    query: Annotated[
        str,
        Field(
            description="Search query (e.g., 'python image security', 'CVE management')"
        ),
    ],
    max_results: Annotated[
        int,
        Field(
            description="Maximum number of results to return (default: 5)",
            le=MAX_RESULTS_CAP,
        ),
    ] = 5,
) -> str:
    if docs_index is None:
        return DOCS_UNAVAILABLE

    query = query[:MAX_INPUT_LEN]
    max_results = min(max_results, MAX_RESULTS_CAP)
    results = docs_index.search(query, max_results)

    if not results:
        return f"No results found for query: {query}"

    response = f"# Search Results for: {query}\n\n"
    for i, result in enumerate(results, 1):
        response += f"## Result {i}: {result['section']}\n\n"
        if result["url"]:
            response += f"{result['url']}\n\n"
        response += f"{result['snippet']}\n\n"
        response += "---\n\n"
    return response


@server.tool(
    description="Get security-related documentation including CVE management and SBOMs"
)
@safe_tool
def get_security_docs() -> str:
    if docs_index is None:
        return DOCS_UNAVAILABLE
    return docs_index.get_security_content()


@server.tool(
    description="Get documentation for Chainguard tools (wolfi, apko, melange, chainctl)"
)
@safe_tool
def get_tool_docs(
    tool_name: Annotated[
        str, Field(description="Tool name: wolfi, apko, melange, or chainctl")
    ],
) -> str:
    if docs_index is None:
        return DOCS_UNAVAILABLE

    tool_name = tool_name[:MAX_INPUT_LEN]
    docs = docs_index.get_tool_docs(tool_name)

    if docs:
        return f"# {tool_name.title()} Documentation\n\n{docs}"
    return f"No documentation found for tool: {tool_name}"


@server.tool(
    description="Find Wolfi package equivalents for Debian, Fedora, or Alpine packages (e.g., Debian 'build-essential' -> Wolfi 'build-base')"
)
@safe_tool
def find_package_equivalent(
    package: Annotated[
        str,
        Field(
            description="OS package name (e.g., 'build-essential', 'libssl-dev', 'python3-pip')"
        ),
    ],
    distro: Annotated[
        Optional[Literal["debian", "fedora", "alpine"]],
        Field(
            description="Source distro to search: 'debian', 'fedora', or 'alpine'. Searches all if omitted."
        ),
    ] = None,
) -> str:
    package = package[:MAX_INPUT_LEN]
    if not catalog.available:
        return "Package catalog not available. Cannot look up package equivalents."

    results = catalog.find_package_equivalent(package, distro)
    if results:
        response = f"# Wolfi Equivalents for `{package}`\n\n"
        for r in results:
            wolfi_pkgs = (
                ", ".join(r["wolfi_packages"])
                if r["wolfi_packages"]
                else "(no direct equivalent)"
            )
            response += (
                f"- **{r['distro']}** `{r['original_package']}` -> `{wolfi_pkgs}`\n"
            )
        response += "\nInstall in a Wolfi-based image with:\n```\napk add "
        # Use first result's wolfi packages
        first_pkgs = results[0]["wolfi_packages"]
        response += " ".join(first_pkgs) if first_pkgs else "<package>"
        response += "\n```"
        return response
    else:
        search_note = f" in {distro}" if distro else ""
        return f"No Wolfi package equivalent found for `{package}`{search_note}. The package may use the same name in Wolfi, or check https://packages.wolfi.dev"


@server.tool(
    description="Find the Chainguard container image that replaces an upstream image, such as Docker Hub's bitnami/pgpool, using the Dockerfile Converter (dfc) mappings. Returns the image name and a pull reference of the form cgr.dev/<your-organization>/<image>."
)
@safe_tool
def find_image_equivalent(
    image: Annotated[
        str,
        Field(
            description="Upstream image reference as it appears in a FROM line (e.g., 'bitnami/pgpool', 'docker.io/library/node:20', 'gcr.io/kaniko-project/executor')"
        ),
    ],
) -> str:
    image = image[:MAX_INPUT_LEN]
    if not catalog.available:
        return "Package catalog not available. Cannot look up image equivalents."

    match = catalog.find_image_equivalent(image)
    if match is None:
        name, _ = split_image_reference(image.strip())
        kept = name.rsplit("/", 1)[-1]
        return (
            f"No dfc mapping for `{image}`. With no mapping, dfc keeps the image's "
            f"own name, `{kept}`, which may or may not be a Chainguard image. Search "
            "the Chainguard Containers Directory at https://images.chainguard.dev/ "
            "to check."
        )

    reference = f"cgr.dev/<your-organization>/{match['image']}"
    if match["tag"]:
        reference += f":{match['tag']}"

    response = f"# Chainguard equivalent for `{image}`\n\n"
    response += f"- **Chainguard image**: `{match['image']}`\n"
    response += f"- **Pull reference**: `{reference}`\n"
    response += f"- **Matched dfc mapping**: `{match['matched']}`\n\n"
    response += (
        "Replace `<your-organization>` with your Chainguard organization's name. "
        "Most Chainguard images are available only to organizations entitled to "
        "them, so the public `cgr.dev/chainguard` namespace may not serve this one. "
        "Check that your organization can pull it with the cg-oci MCP server "
        "(https://cgr.dev/mcp), or see the image's page at "
        f"https://images.chainguard.dev/directory/image/{match['image']}/overview"
    )
    return response


def parse_args():
    """Parse command-line arguments with env var fallbacks."""
    parser = argparse.ArgumentParser(
        description="Chainguard AI Documentation MCP Server"
    )
    parser.add_argument(
        "--transport",
        choices=["stdio", "http"],
        default=os.getenv("MCP_TRANSPORT", "stdio"),
        help="Transport mode (default: stdio, env: MCP_TRANSPORT)",
    )
    parser.add_argument(
        "--host",
        # Binding all interfaces is required inside the Cloud Run container; the
        # service is fronted by Cloud Run, not exposed on the host directly.
        default=os.getenv("MCP_HOST", "0.0.0.0"),  # nosec B104
        help="HTTP server host (default: 0.0.0.0, env: MCP_HOST)",
    )
    parser.add_argument(
        "--port",
        type=int,
        default=int(os.getenv("MCP_PORT", "8080")),
        help="HTTP server port (default: 8080, env: MCP_PORT)",
    )
    return parser.parse_args()


if __name__ == "__main__":
    args = parse_args()

    if args.transport == "http":
        # host must be passed explicitly: the SDK runner defaults to 127.0.0.1,
        # but Cloud Run requires binding 0.0.0.0. streamable_http_path defaults
        # to "/mcp" (matches the 1.x mount) and max_request_body_size to 4 MiB.
        #
        # stateless_http holds no per-session state in instance memory. The
        # service runs multiple Cloud Run instances behind a global load
        # balancer with no session affinity, so a session minted by initialize
        # on one instance is rejected with 404 "Session not found" when a
        # follow-up request (e.g. notifications/initialized) lands on another
        # (CUS-1340). The docs tools are read-only with no server-initiated
        # notifications, so holding no shared session state has no downside.
        # Statelessness also retires the SDK's per-session ceilings
        # (max_sessions, session_idle_timeout); throughput is now bounded by
        # Cloud Run per-instance concurrency instead.
        #
        # json_response returns each POST reply as a single application/json
        # body instead of a one-shot text/event-stream. These tools are
        # read-only and single-response, so nothing needs SSE framing, and plain
        # JSON is friendlier to the fronting load balancer and buffering proxies.
        logger.info(
            "Starting HTTP transport with stateless_http=True, json_response=True (CUS-1340)"
        )
        server.run(
            transport="streamable-http",
            host=args.host,
            port=args.port,
            stateless_http=True,
            json_response=True,
        )
    else:
        server.run()  # stdio
