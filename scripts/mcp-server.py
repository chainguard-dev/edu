#!/usr/bin/env python3
"""
Chainguard AI Documentation MCP Server

A Model Context Protocol server that provides AI assistants with searchable
access to Chainguard documentation, security guides, and tooling references,
plus Debian and Fedora to Wolfi package mappings.

Container image data moved to Chainguard's product MCP servers, which read the
registry live: this server's image tools were built from a README snapshot that
had stopped updating (DOCS-138). SERVER_INSTRUCTIONS below points clients there.

Ported to the mcp 2.0 high-level `MCPServer` API (decision: DOCS-89). All tool
logic and both index classes are unchanged from the 1.x server; only the MCP
glue (registration + transport) was rewritten.
"""

