@server.tool(
    description="List available Chainguard container images with optional filtering"
)
@safe_tool
def list_images(
    # Named `filter` to preserve the 1.x tool's argument name; shadows the builtin
    # only within this function.
    filter: Annotated[
        Optional[str],
        Field(description="Filter images by name (e.g., 'python', 'nginx', 'go')"),
    ] = None,
) -> str:
    filter_term = filter[:MAX_INPUT_LEN] if filter else None

    # Use catalog if available for richer results
    if catalog.available:
        results = catalog.list_images(filter_term)
        if not results:
            return f"No images found matching filter: {filter_term}"

        response = f"# Chainguard Container Images ({len(results)} results)\n\n"
        for img in results:
            line = f"- **{img['name']}** (`{img['registry_ref']}`)"
            if img.get("has_documentation"):
                line += " [docs]"
            response += line + "\n"
        return response
    else:
        # Fallback to docs-only listing
        images = docs_index.images if docs_index else []
        if filter_term:
            images = [i for i in images if filter_term.lower() in i.lower()]
        images_list = "\n".join([f"- {img}" for img in images])
        return f"# Available Chainguard Container Images\n\n{images_list}"


