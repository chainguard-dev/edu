"""Generate the capabilities table on the built-in roles reference page.

Usage: python3 scripts/capabilities-table/generate.py ROLES_JSON [--check]

ROLES_JSON is the saved output of `chainctl iam roles list -o json`.

The table lists every resource that a documented role grants a capability
on, and which documented roles hold which actions on it. A capability name
splits into a resource and an action at its last dot: repo.blobs.get is the
get action on the repo.blobs resource.

purposes.toml, next to this script, holds the hand-written parts: the roles
the page documents, resources it leaves out, and the Purpose text per
resource. The script rewrites only the text between the BEGIN and END
markers on the page.

The script stops with an error, and changes nothing, when:
- a documented role isn't a deployed system role
- a resource a documented role grants has no Purpose text
- a Purpose or omitted entry names a resource no documented role grants

With --check, the script writes nothing. It exits 1 if the page differs
from what it would generate.

Standard library only.
"""

import argparse
import json
import sys
import tomllib
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
REPO_ROOT = SCRIPT_DIR.parent.parent
PURPOSES_FILE = SCRIPT_DIR / "purposes.toml"
PAGE_FILE = (
    REPO_ROOT
    / "content/platform/administration/iam-organizations"
    / "roles-role-bindings/capabilities-reference.md"
)

BEGIN_MARKER = "<!-- BEGIN generated by scripts/capabilities-table/generate.py -->"
END_MARKER = "<!-- END generated by scripts/capabilities-table/generate.py -->"

TABLE_HEADER = (
    "| Resource | Purpose | Roles with access to this resource |\n"
    "|------------|---------|---------------------------|\n"
)


def load_system_roles(roles_json_path):
    """Return {role name: list of capabilities} for every system role."""
    with open(roles_json_path) as f:
        data = json.load(f)

    system_roles = {}
    for role in data["items"]:
        if role.get("type") == "system":
            system_roles[role["name"]] = role.get("capabilities", [])
    return system_roles


def split_capability(capability):
    """Split repo.blobs.get into ("repo.blobs", "get")."""
    resource, _, action = capability.rpartition(".")
    return resource, action


def collect_access(documented_roles, system_roles):
    """Return {resource: {role: set of actions}} for the documented roles."""
    access = {}
    for role in documented_roles:
        for capability in system_roles[role]:
            resource, action = split_capability(capability)
            if resource == "":
                # A capability with no dot has no resource to put in a row.
                raise SystemExit(
                    f"error: role {role} grants capability {capability!r}, "
                    "which has no resource part"
                )
            roles_for_resource = access.setdefault(resource, {})
            roles_for_resource.setdefault(role, set()).add(action)
    return access


def find_problems(omitted, purposes, access):
    """Return a list of error messages. An empty list means all is well."""
    problems = []

    for resource in sorted(access):
        if resource not in purposes and resource not in omitted:
            roles = ", ".join(access[resource])
            problems.append(
                f"resource {resource} (granted by {roles}) has no Purpose "
                "text in purposes.toml"
            )

    for resource in sorted(purposes):
        if resource not in access:
            problems.append(
                f"purposes.toml has Purpose text for {resource}, "
                "but no documented role grants it"
            )
        if resource in omitted:
            problems.append(f"{resource} is in both purposes and omitted_resources")

    for resource in sorted(omitted):
        if resource not in access:
            problems.append(
                f"omitted_resources lists {resource}, "
                "but no documented role grants it"
            )

    return problems


def render_row(resource, purpose, roles_with_actions, documented_roles):
    """Render one table row, with roles in the order purposes.toml lists them."""
    items = []
    for role in documented_roles:
        if role in roles_with_actions:
            actions = ", ".join(sorted(roles_with_actions[role]))
            items.append(f"<li>`{role}` ({actions})</li>")
    cell = "<ul>" + "".join(items) + "</ul>"
    return f"| `{resource}` | {purpose} | {cell} |\n"


def render_table(documented_roles, omitted, purposes, access):
    rows = []
    for resource in sorted(access):
        if resource in omitted:
            continue
        rows.append(
            render_row(resource, purposes[resource], access[resource], documented_roles)
        )
    return TABLE_HEADER + "".join(rows)


def replace_generated_region(page_text, table):
    """Return page_text with the text between the markers replaced by table."""
    if page_text.count(BEGIN_MARKER) != 1 or page_text.count(END_MARKER) != 1:
        raise SystemExit(
            f"error: {PAGE_FILE} must contain each marker exactly once:\n"
            f"  {BEGIN_MARKER}\n  {END_MARKER}"
        )

    before, rest = page_text.split(BEGIN_MARKER)
    _, after = rest.split(END_MARKER)
    return before + BEGIN_MARKER + "\n\n" + table + "\n" + END_MARKER + after


def main():
    parser = argparse.ArgumentParser(
        description="Generate the capabilities table on the built-in roles reference page."
    )
    parser.add_argument(
        "roles_json", help="saved output of `chainctl iam roles list -o json`"
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="write nothing; exit 1 if the page is out of date",
    )
    args = parser.parse_args()

    with open(PURPOSES_FILE, "rb") as f:
        config = tomllib.load(f)
    documented_roles = config["roles"]
    omitted = set(config.get("omitted_resources", []))
    purposes = config["purposes"]

    system_roles = load_system_roles(args.roles_json)

    missing_roles = [role for role in documented_roles if role not in system_roles]
    if missing_roles:
        for role in missing_roles:
            print(
                f"error: documented role {role} is not a deployed system role",
                file=sys.stderr,
            )
        return 1

    access = collect_access(documented_roles, system_roles)
    problems = find_problems(omitted, purposes, access)
    if problems:
        for problem in problems:
            print(f"error: {problem}", file=sys.stderr)
        print(
            "Edit scripts/capabilities-table/purposes.toml, then run again.",
            file=sys.stderr,
        )
        return 1

    table = render_table(documented_roles, omitted, purposes, access)
    page_text = PAGE_FILE.read_text()
    new_page_text = replace_generated_region(page_text, table)

    if args.check:
        if new_page_text == page_text:
            print("The capabilities table is up to date.")
            return 0
        print(
            f"The capabilities table in {PAGE_FILE.relative_to(REPO_ROOT)} is "
            "out of date. Run this script without --check to update it."
        )
        return 1

    if new_page_text == page_text:
        print("No changes.")
    else:
        PAGE_FILE.write_text(new_page_text)
        print(f"Updated {PAGE_FILE.relative_to(REPO_ROOT)}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
